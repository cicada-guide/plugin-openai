import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { createHash } from 'node:crypto';
import { zipSync, unzipSync } from 'fflate';
import { root, checkSource, checkFiles } from './check.mjs';
const { files } = checkSource();
const entries = Object.fromEntries(Object.entries(files).map(([p, data]) => [`cicada-guide/${p}`, [data, { mtime: new Date('2026-11-02T00:00:00Z') }]]));
mkdirSync(resolve(root, 'dist'), { recursive: true });
const archive = resolve(root, 'dist/cicada-guide-0.1.0.zip');
writeFileSync(archive, zipSync(entries, { level: 9 }));
const reopened = unzipSync(readFileSync(archive));
const extracted = Object.fromEntries(Object.entries(reopened).map(([p, data]) => [p.replace(/^cicada-guide\//, ''), data]));
if (Object.keys(reopened).some(p => !p.startsWith('cicada-guide/'))) throw new Error('Invalid archive wrapper');
if (JSON.stringify(Object.keys(extracted).sort()) !== JSON.stringify(Object.keys(files).sort())) throw new Error('Archive inventory changed');
for (const [p, data] of Object.entries(files)) if (!Buffer.from(extracted[p]).equals(data)) throw new Error(`Archive bytes differ: ${p}`);
const result = checkFiles(extracted);
if (result.failures.length) throw new Error(result.failures.join('\n'));
const sha256 = createHash('sha256').update(readFileSync(archive)).digest('hex');
writeFileSync(resolve(root, 'dist/archive-report.json'), JSON.stringify({ archive, sha256, entries: Object.keys(reopened), submissionGaps: result.submissionGaps, readiness: 'prepared but not submission-ready' }, null, 2) + '\n');
console.log(`Verified ZIP: ${archive}\nSHA256 ${sha256}\nPrepared but not submission-ready; see docs/readiness.md.`);
